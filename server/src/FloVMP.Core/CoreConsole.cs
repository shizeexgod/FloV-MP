namespace FloVMP.Core;

/// <summary>
/// Куда платформа пишет диагностику установки: режим хранилища, накат
/// миграций, выбор хранилища блокировок, состояние голоса.
///
/// Зачем отдельный класс. Раньше всё это шло прямым
/// <c>Console.WriteLine</c> — и не доходило вообще никуда: alt:V пишет в свой
/// лог только то, что прошло через <c>Alt.Log</c>, а обычный вывод в консоль
/// ресурса теряется. Проверено живым запуском: строки «Блокировки: локальный
/// файл…» и «Миграции применены…» в server.log не появлялись ни разу.
///
/// Именно эти сообщения нужны тому, кто ставит сервер: по ним видно, ушла ли
/// база на JSON, накатилась ли схема, действуют ли баны на всех инстансах.
/// Терять их — значит отлаживать установку вслепую.
///
/// FloVMP.Core намеренно не зависит от AltV.Net, поэтому ресурс сам
/// подставляет сюда <c>Alt.Log</c> при старте.
/// </summary>
public static class CoreConsole
{
    /// <summary>
    /// Приёмник строк. По умолчанию обычная консоль — так работают юнит-тесты
    /// и нагрузочный стенд, где alt:V нет.
    /// </summary>
    public static Action<string> Out { get; set; } = Console.WriteLine;

    /// <summary>Приёмник предупреждений. По умолчанию тот же, что и обычный.</summary>
    public static Action<string> Warn { get; set; } = Console.WriteLine;

    public static void Write(string message)
    {
        try { Out(message); }
        catch { /* логирование не имеет права ронять старт сервера */ }
    }

    public static void Warning(string message)
    {
        try { Warn(message); }
        catch { /* см. выше */ }
    }
}
