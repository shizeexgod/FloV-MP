namespace FloVMP.Core.Admin;

/// <summary>
/// 8-уровневая иерархия администрации FloV:MP (согласно AGENTS.md).
/// </summary>
public enum AdminRank
{
    None = 0,
    Helper = 1,        // Мл. Модератор / Помощник по репорту
    Moderator = 2,     // Модератор
    SeniorMod = 3,     // Старший модератор
    Admin = 4,         // Администратор
    SeniorAdmin = 5,   // Старший администратор
    Curator = 6,       // Куратор / Зам. Главного Администратора (ЗГА)
    MainAdmin = 7,     // Главный Администратор (ГА)
    Owner = 8          // Руководитель проекта / Спец. Администратор
}

public static class AdminTitles
{
    public static string GetTitle(int level) => level switch
    {
        1 => "Мл. Модератор",
        2 => "Модератор",
        3 => "Ст. Модератор",
        4 => "Администратор",
        5 => "Ст. Администратор",
        6 => "Куратор",
        7 => "Главный Администратор",
        8 => "Руководитель проекта",
        _ => "Игрок"
    };

    public static string GetPrefix(int level) => level switch
    {
        1 => "[Хелпер]",
        2 => "[Модератор]",
        3 => "[Ст. Модер]",
        4 => "[Администратор]",
        5 => "[Ст. Админ]",
        6 => "[Куратор]",
        7 => "[ГА]",
        8 => "[Руководитель]",
        _ => ""
    };

    public static string GetColor(int level) => level switch
    {
        1 => "#22c55e", // зеленый
        2 => "#06b6d4", // бирюзовый
        3 => "#3b82f6", // синий
        4 => "#8b5cf6", // фиолетовый
        5 => "#ec4899", // розовый
        6 => "#f97316", // оранжевый
        7 => "#ef4444", // красный
        8 => "#eab308", // золотой
        _ => "#ffffff"
    };
}
