#pragma once
// Скачивание файлов по HTTP для клиента FloV:MP.
//
// Нужно ровно для одного: владелец сервера указывает в настройках ссылку на
// фон и логотип загрузочного экрана, и клиент забирает их к себе в кэш. Всё
// остальное общение с сервером идёт по нашему протоколу FLOV/2.
//
// Движок — WinHTTP, он входит в Windows. Своей реализации HTTP и сторонних
// библиотек в клиенте нет и не нужно.

#include <string>

namespace flov::http
{
    /// Наибольший размер загружаемого файла. Фон загрузочного экрана — это
    /// картинка, а не дистрибутив: ограничение защищает игрока от сервера,
    /// который по ошибке или намеренно отдаст гигабайт.
    constexpr size_t kMaxBytes = 16u * 1024u * 1024u;

    /// Скачать по ссылке во временный файл и переименовать в destination.
    /// Возвращает false при любой ошибке; причина уходит в журнал клиента.
    /// Вызывать только из рабочего потока: функция блокирующая.
    bool Download(const std::string& url, const std::wstring& destination);

    /// Имя файла в кэше по ссылке: SHA-256 от строки, шестнадцатеричный вид.
    /// Расширение не нужно — формат картинки определяется по содержимому.
    std::string CacheName(const std::string& url);
}
