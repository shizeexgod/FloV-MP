#pragma once
// Отчёты о падениях игры (пункт 12 roadmap).
//
// Когда игра падает, Windows вызывает обработчик необработанных исключений.
// Наш пишет в %LOCALAPPDATA%\FloVMP\crashes мини-дамп (для разбора в Visual
// Studio / WinDbg) и короткую сводку, а при следующем входе на сервер клиент
// отправляет одну строку: где упало. Сам дамп остаётся у игрока — в нём
// память процесса, её мы никуда не шлём.

#include <string>
#include <vector>

namespace flov::crash
{
    /// Поставить обработчик. Игра и другие моды могут поставить свой поверх —
    /// поэтому вызывается повторно (при старте скрипта и при каждом входе).
    /// Прежний обработчик не теряется: после записи дампа управление уходит ему.
    void Install();

    /// Неотправленный отчёт прошлого падения: поля строки CRASH после имени
    /// (код, модуль, смещение, версия клиента, секунд назад, версия игры).
    /// false — отчёта нет.
    bool TakePending(std::vector<std::string>& fields);

    /// Отчёт ушёл на сервер — больше его не слать.
    void MarkSent();
}
